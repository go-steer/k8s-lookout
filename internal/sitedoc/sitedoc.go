// Header is stamped on every generated page, right after the
// frontmatter, so a human editing one by hand is warned before the
// drift test tells them the hard way.
const Header = "<!-- Generated by dev/tools/gen-site-docs (internal/sitedoc). DO NOT EDIT: edit the command metadata / flag declarations / ledgers and re-run the generator. -->"

// Dir is the generated-only directory, relative to the repo root.
// Every .md file under it is owned by this package; hand-written
// reference material belongs in another section.
const Dir = "docs/site/src/content/docs/reference"

// DetectDir is the "What lookout detects" section: one coverage page
// per mode, so a reader landing on the site can find what each of the
// three things the binary does actually looks for, without assembling
// it from an alphabetical 147-row glossary.
//
// Unlike Dir this directory is NOT generated-only, and the generator's
// stale sweep deliberately does not run over it: `sentinel.md` is
// hand-written narrative, because the sentinel's coverage map ("what
// fails / example trigger / what it costs to enable") is not derivable
// from any declaration — it is editorial, and pinned instead by the
// tests in internal/watch. The scan and audit pages ARE derivable —
// scan's composition is declared in pkg/checks/scan and audit's is its
// registry group — so they are generated here and cannot drift.
const DetectDir = "docs/site/src/content/docs/detect"

// GenerateAll renders the Reference section plus the two generated
// coverage pages. Keys are paths relative to the repository root.
func GenerateAll(reg *checks.Registry) map[string]string {
	out := map[string]string{
		Dir + "/index.md":         indexPage(reg),
		Dir + "/watch.md":         watchPage(),
		Dir + "/signal-kinds.md":  kindsPage(),
		Dir + "/finding-kinds.md": findingKindsPage(reg),
		Dir + "/metrics.md":       metricsPage(),

		DetectDir + "/index.md": detectIndexPage(),
		DetectDir + "/scan.md":  scanCoveragePage(reg),
		DetectDir + "/audit.md": auditCoveragePage(reg),
	}
	for _, c := range reg.All() {
		if c.Hidden {
			continue
		}
		out[Dir+"/"+PageFileName(c.Name)+".md"] = commandPage(c)
	}
	return out
}

// PageFileName returns the page slug for a command name:
// "triage delta" → "triage-delta".
func PageFileName(command string) string {
	return strings.ReplaceAll(command, " ", "-")
}

// ---- command pages ----------------------------------------------------

func commandPage(c checks.Command) string {
	var b strings.Builder
	frontmatter(&b, "lookout "+c.Name, c.Summary)

	fmt.Fprintf(&b, "%s\n\nMCP tool: `%s`%s\n\n", escapeProse(c.Summary), c.MCPName, c.MCPProfileNote())

	b.WriteString("## Usage\n\n")
	if c.Positional != nil {
		fmt.Fprintf(&b, "```sh\nlookout %s %s [flags]\n```\n\n", c.Name, c.Positional.Meta)
		fmt.Fprintf(&b, "`%s` — %s\n\n", c.Positional.Meta, escapeProse(c.Positional.Doc))
	} else {
		fmt.Fprintf(&b, "```sh\nlookout %s [flags]\n```\n\n", c.Name)
	}

	if len(c.Flags) > 0 {
		b.WriteString("## Flags\n\n")
		writeSpecTable(&b, c.Flags)
	}
	b.WriteString("## Common flags (every `lookout` command)\n\n")
	writeSpecTable(&b, c.CommonFlags())
	if c.GraphBacked {
		b.WriteString("## Point-in-time flags (graph-backed commands)\n\n")
		b.WriteString("This command answers from the topology graph and accepts the point-in-time flags:\n\n")
		writeSpecTable(&b, emit.GraphHistoryFlags())
	}

	if len(c.Kinds) > 0 {
		b.WriteString("## Finding kinds\n\nEvery `kind=` this command can emit, and the severities it carries them at. " +
			"Nothing else appears in its output; a kind absent from a run means the check looked and found nothing. " +
			"See the [finding-kind glossary](/reference/finding-kinds/) for the whole vocabulary.\n\n")
		b.WriteString("| Kind | Severity | Claim |\n| --- | --- | --- |\n")
		for _, k := range c.Kinds {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", k.Name, strings.Join(k.Severity, ", "), cell(escapeProse(k.Doc)))
		}
		b.WriteString("\n")
	}

	if len(c.Output) > 0 {
		fmt.Fprintf(&b, "## Output fields\n\nBeyond the shared envelope fields (%s):\n\n",
			"`"+strings.Join(emit.EnvelopeFields(), "`, `")+"`")
		b.WriteString("| Field | Meaning |\n| --- | --- |\n")
		for _, f := range c.Output {
			fmt.Fprintf(&b, "| `%s` | %s |\n", f.Name, cell(f.Doc))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Output contract\n\n" + checks.EnvelopeContract() + "\n")

	if len(c.Examples) > 0 {
		b.WriteString("\n## Examples\n\n```sh\n")
		for _, e := range c.Examples {
			b.WriteString(e + "\n")
		}
		b.WriteString("```\n")
	}
	return b.String()
}

// writeSpecTable renders emit.FlagSpec rows with the declared type,
// defaults inline — the docs-site variant of skilldoc's flag table.
func writeSpecTable(b *strings.Builder, specs []emit.FlagSpec) {
	b.WriteString("| Flag | Type | Default | Meaning |\n| --- | --- | --- | --- |\n")
	for _, s := range specs {
		dash := "--"
		if len(s.Name) == 1 {
			dash = "-"
		}
		def := s.Default
		switch {
		case s.Type == emit.FlagBool, def == "", def == "0s", def == "0":
			def = "—"
		default:
			def = "`" + def + "`"
		}
		fmt.Fprintf(b, "| `%s%s` | %s | %s | %s |\n", dash, s.Name, s.Type, def, cell(s.Help))
	}
	b.WriteString("\n")
}

