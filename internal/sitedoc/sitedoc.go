// Package sitedoc generates the docs-site Reference section under
// docs/site/src/content/docs/reference/ — the fourth generated
// surface after --help, the MCP schemas, and the skill reference
// stubs (DESIGN.md §4.4.3: one source of truth, generated outward).
//
// Inputs, all exported data or registries so nothing here is
// hand-maintained twice:
//   - pkg/checks command metadata (one page per registered command,
//     plus the finding-kind glossary unioned from their Kinds
//     ledgers),
//   - internal/watch.FlagInventory (the sentinel page, derived from
//     the real FlagSet),
//   - pkg/inject/schema.Kinds (the signal-kind catalog, the same
//     ledger the v1 freeze test pins),
//   - internal/watch.MetricsInventory (the Prometheus metrics page,
//     names + help derived from the live collectors).
//
// The committed pages are regenerated by dev/tools/gen-site-docs; a
// drift test in this package fails CI when a metadata change is not
// followed by a re-run, exactly like internal/skilldoc.
