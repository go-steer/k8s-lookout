// writeCoverageStage renders one command as a coverage section: the
// heading is the command (and the follow-up call), the prose is its own
// one-line summary, and the table is its declared kinds. The level is
// the caller's because the two pages nest differently — scan's stages
// sit under a stage heading, audit's subcommands are the top level.
func writeCoverageStage(b *strings.Builder, c checks.Command, level string) {
	fmt.Fprintf(b, "%s [`lookout %s`](/reference/%s/)\n\n%s\n\n",
		level, c.Name, PageFileName(c.Name), escapeProse(c.Summary))
	writeKindTable(b, c.Kinds)
}

// countKinds counts the distinct kinds a set of commands declares —
// the group's claim count, derived rather than typed into prose.
func countKinds(cmds []checks.Command) int {
	seen := map[string]bool{}
	for _, c := range cmds {
		for _, k := range c.Kinds {
			seen[k.Name] = true
		}
	}
	return len(seen)
}

// numberWord spells small counts, so derived prose reads like prose.
// Above the range a bare numeral is fine — nobody writes "twenty-three"
// in a sentence about flags.
func numberWord(n int) string {
	words := []string{"zero", "one", "two", "three", "four", "five",
		"six", "seven", "eight", "nine", "ten"}
	if n >= 0 && n < len(words) {
		return words[n]
	}
	return strconv.Itoa(n)
}

// upperFirst capitalizes a summary written as a mid-sentence fragment
// (group summaries are phrased for `--help`) so it can stand alone as a
// paragraph under a heading.
func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// writeKindTable is the coverage pages' kind table: the claim column
// carries the whole point, so it is last and unabbreviated.
func writeKindTable(b *strings.Builder, kinds []checks.KindField) {
	if len(kinds) == 0 {
		return
	}
	b.WriteString("| Kind | Severity | What it means |\n| --- | --- | --- |\n")
	for _, k := range kinds {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", k.Name, strings.Join(k.Severity, ", "), cell(escapeProse(k.Doc)))
	}
	b.WriteString("\n")
}

// ---- shared helpers --------------------------------------------------------

// frontmatter writes the Starlight frontmatter followed by the
// generated-file header. The header must come AFTER the frontmatter
// (Starlight requires the file to open with it).
func frontmatter(b *strings.Builder, title, description string) {
	fmt.Fprintf(b, "---\ntitle: %s\ndescription: %s\n---\n\n%s\n\n",
		yamlQuote(title), yamlQuote(stripSpecRefs(description)), Header)
}

// frontmatterOrdered is frontmatter for a section whose sidebar order
// is curated rather than alphabetical.
func frontmatterOrdered(b *strings.Builder, title, description string, order int) {
	fmt.Fprintf(b, "---\ntitle: %s\ndescription: %s\nsidebar:\n  order: %d\n---\n\n%s\n\n",
		yamlQuote(title), yamlQuote(stripSpecRefs(description)), order, Header)
}

// ---- design-doc citation stripping ------------------------------------

// The command metadata, flag help strings, kind docs, and metric help
// cite DESIGN.md sections ("§9.4", "(DESIGN.md §7)", "§15 Q2"). Those
// citations are useful in --help and the MCP tool descriptions, whose
// readers work inside the repository — but they are noise on the
// user-facing docs site. The site emitter strips them at render time,
// here, so the source metadata keeps its citations and the other
// generated surfaces are untouched. The passes, in order:
//
//  1. a parenthetical that is only a citation (or several) is dropped
//     whole: "(§9.4)", "(DESIGN.md §11)", "(§7.4 + §7.5)"; the
//     "(§2 marker)" shorthand for the unavailable marker drops too;
//  2. a citation opening a parenthetical loses just the citation and
//     its separator: "(§15 Q3: fixed budget…)" → "(fixed budget…)",
//     "(§8, sha256:…)" → "(sha256:…)";
//  3. a citation closing a parenthetical likewise:
//     "(per-incident mode; §7.7)" → "(per-incident mode)";
//  4. "per §X" clauses drop with the citation;
//  5. any remaining inline token drops: "the §9.2 distiller pass" →
//     "the distiller pass".
//
// A doc string that OPENED with a citation ("§7.4 outcome record: …")
// is re-capitalized after the strip.
const specRef = `(?:DESIGN\.md )?§[0-9]+(?:\.[0-9]+)*(?: Q[0-9]+)?`

var (
	refParenOnly = regexp.MustCompile(`\s*\(` + specRef + `(?:\s*[+,;/&]\s*` + specRef + `)*\)`)
	refMarker    = regexp.MustCompile(`\s*\(` + specRef + ` marker\)`)
	refParenLead = regexp.MustCompile(`\(` + specRef + `\s*[:;,]\s*`)
	refParenTail = regexp.MustCompile(`\s*[;,]\s*` + specRef + `\)`)
	refPerClause = regexp.MustCompile(`,?\s+per ` + specRef)
	refInline    = regexp.MustCompile(specRef + ` `)
	refBare      = regexp.MustCompile(`\s*` + specRef)
)

// stripSpecRefs removes DESIGN.md section citations from metadata
// prose bound for the docs site (see the policy comment above).
func stripSpecRefs(s string) string {
	openedWithRef := strings.HasPrefix(s, "§") || strings.HasPrefix(s, "DESIGN.md §")
	s = refMarker.ReplaceAllString(s, "")
	s = refParenOnly.ReplaceAllString(s, "")
	s = refParenLead.ReplaceAllString(s, "(")
	s = refParenTail.ReplaceAllString(s, ")")
	s = refPerClause.ReplaceAllString(s, "")
	s = refInline.ReplaceAllString(s, "")
	s = refBare.ReplaceAllString(s, "")
	s = strings.Join(strings.Fields(s), " ")
	if openedWithRef && len(s) > 0 && 'a' <= s[0] && s[0] <= 'z' {
		s = string(s[0]-'a'+'A') + s[1:]
	}
	return s
}

// yamlQuote renders a YAML double-quoted scalar.
func yamlQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// cell escapes a string for use inside a markdown table cell: raw
// '<' outside code spans (would parse as HTML) and every '|' (would
// split the cell — pipes break GFM tables even inside code spans).
func cell(s string) string { return strings.ReplaceAll(escapeProse(s), "|", "\\|") }

// escapeProse prepares metadata prose for the site's markdown OUTSIDE
// `code spans` (inside them everything is already literal): raw '<'
// is backslash-escaped so placeholder tokens like <Kind> render as
// text instead of parsing as HTML, and bare product names get the
// site's code formatting (`k8s-lookout` the project, `lookout` the
// binary) — the docs-site convention; --help and the MCP schemas
// render the same metadata without backticks, so the formatting is
// applied here, never in the source strings. DESIGN.md section
// citations are stripped first, for the same reason in reverse: they
// belong on the repository-facing surfaces, not the site.
func escapeProse(s string) string {
	parts := strings.Split(stripSpecRefs(s), "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = codeProductNames(strings.ReplaceAll(parts[i], "<", `\<`))
	}
	return strings.Join(parts, "`")
}

// productName matches a product-name token; boundary checks in
// codeProductNames keep it from firing inside paths, image refs, or
// filenames ("go-steer/k8s-lookout", "ghcr.io/go-steer/lookout",
// "lookout.db").
var productName = regexp.MustCompile(`k8s-lookout|lookout`)

// codeProductNames wraps bare "k8s-lookout" / "lookout" tokens in
// backticks. A token is bare when it is not glued to identifier, path,
// or hostname characters on either side; a trailing '.' counts as
// sentence punctuation unless it starts an extension ("lookout.db").
func codeProductNames(s string) string {
	wordy := func(c byte) bool {
		return c == '_' || c == '-' || c == '/' ||
			('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z') || ('0' <= c && c <= '9')
	}
	var b strings.Builder
	last := 0
	for _, m := range productName.FindAllStringIndex(s, -1) {
		start, end := m[0], m[1]
		if start > 0 && (wordy(s[start-1]) || s[start-1] == '.') {
			continue
		}
		if end < len(s) && (wordy(s[end]) ||
			(s[end] == '.' && end+1 < len(s) && wordy(s[end+1]) && s[end+1] != '-' && s[end+1] != '/')) {
			continue
		}
		b.WriteString(s[last:start])
		b.WriteByte('`')
		b.WriteString(s[start:end])
		b.WriteByte('`')
		last = end
	}
	b.WriteString(s[last:])
	return b.String()
}

// SortedPaths returns the generated paths in stable order (test and
// generator logging convenience).
func SortedPaths(files map[string]string) []string {
	out := make([]string, 0, len(files))
	for p := range files {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}
