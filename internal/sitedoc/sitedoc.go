// ---- the section index ----------------------------------------------------

func indexPage(reg *checks.Registry) string {
	var b strings.Builder
	frontmatter(&b, "Reference",
		"Generated reference: every read-path command, the watch sentinel's flags, the signal-kind catalog, and the Prometheus metrics.")
	b.WriteString("" +
		"Every page in this section is generated by `dev/tools/gen-site-docs` from\n" +
		"the same declarations that produce `--help`, the MCP schemas, and the skill\n" +
		"reference stubs (one source of truth, generated outward).\n" +
		"A drift test fails CI when a committed page differs from regeneration.\n\n")

	b.WriteString("## The sentinel\n\n")
	b.WriteString("- [`lookout watch`](/reference/watch/) — the resident per-cluster sentinel: full flag table.\n")
	b.WriteString("- [Signal kinds](/reference/signal-kinds/) — the frozen signal-schema v1 kind catalog.\n")
	b.WriteString("- [Prometheus metrics](/reference/metrics/) — the `--metrics-addr` surface.\n\n")

	b.WriteString("## Read-path commands\n\n")
	b.WriteString("- [Finding kinds](/reference/finding-kinds/) — the whole vocabulary these commands emit, in one table.\n\n")
	if top := reg.TopLevel(); len(top) > 0 {
		b.WriteString("Composed entry points:\n\n")
		for _, c := range top {
			writeIndexRow(&b, c)
		}
		b.WriteString("\n")
	}
	for _, g := range reg.Groups() {
		fmt.Fprintf(&b, "### `lookout %s`\n\n%s\n\n", g, escapeProse(checks.GroupSummary(g)))
		for _, c := range reg.GroupCommands(g) {
			writeIndexRow(&b, c)
		}
		b.WriteString("\n")
	}
	return b.String()
}

func writeIndexRow(b *strings.Builder, c checks.Command) {
	fmt.Fprintf(b, "- [`lookout %s`](/reference/%s/) — %s\n", c.Name, PageFileName(c.Name), escapeProse(c.Summary))
}

